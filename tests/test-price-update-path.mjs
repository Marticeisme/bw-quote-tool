// Proves the price update path by DOING it, end to end, instead of describing it in a doc.
//
// The ask behind sprint-03 was operational, not architectural: Martice changes a price in one
// place, runs one command, and the tool shows the new number. So this suite changes a price,
// runs `sync-prices`, loads the result in a real browser and reads the number off the screen.
//
// Nothing real is written. The price file is copied to the OS temp dir and edited there; the
// synced page is written to index.prices-test.html beside index.html (gitignored, deleted in
// a finally) so the dev server can serve it. Both real files are hashed before and after and
// asserted unchanged — data/prices.json in particular is generated by the map's
// build-prices.py and must never be edited by anything in this repo, tests included.
//
// It also covers the two failure directions:
//   `sync-prices --check` must go RED when the page is behind the file — that is what stops a
//   price change from being half-applied.
//   bwVerifyPriceFile() must notice at RUNTIME when a page is serving prices that disagree
//   with the deployed data/prices.json — that is what catches a deploy of one file and not
//   the other. Here the mismatch is manufactured on purpose, so the banner appearing is a PASS.
//
// Fake Firebase only; production is never contacted.
import { chromium } from 'playwright';
import { execFileSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import crypto from 'crypto';

const FAKE = fs.readFileSync('tests/fake-firebase.js', 'utf8');
const NEW_RECORDING = 999;
const TEST_PAGE = 'index.prices-test.html';

let pass = 0, fail = 0;
const ok = (n, c, x) => {
  if (c) { pass++; console.log('  PASS  ' + n); }
  else { fail++; console.log('  FAIL  ' + n + (x !== undefined ? '\n        ' + JSON.stringify(x) : '')); }
};
const sha = (p) => crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');

const beforeIndex = sha('index.html');
const beforePrices = sha('data/prices.json');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'bw-price-update-'));
const tmpPrices = path.join(tmp, 'prices.json');

let browser = null;
try {
  // ── step 1: the operator's edit, made the way build-prices.py makes it ──────────────────
  const prices = JSON.parse(fs.readFileSync('data/prices.json', 'utf8'));
  const oldRecording = prices.current.fees['RECORDING:all'];
  prices.current.fees['RECORDING:all'] = NEW_RECORDING;
  prices.fees.push({
    code: 'RECORDING', label: 'Recording fee', product: 'all',
    amount: NEW_RECORDING, effective: '2026-07-26',
    source: 'tests/test-price-update-path.mjs (synthetic — never a real price)',
  });
  prices.generated = '2026-07-27';
  fs.writeFileSync(tmpPrices, JSON.stringify(prices, null, 1));

  console.log('\n1. `sync-prices --check` refuses a page that is behind the file');
  let checkFailed = false, checkOut = '';
  try {
    execFileSync(process.execPath,
      ['scripts/sync-prices.mjs', '--check', '--from', tmpPrices, '--into', 'index.html'],
      { encoding: 'utf8', stdio: 'pipe' });
  } catch (e) {
    checkFailed = true;
    checkOut = String(e.stdout || '') + String(e.stderr || '');
  }
  ok('--check exits non-zero when a price has moved', checkFailed, checkOut.slice(0, 200));
  ok('and names the price that moved', /RECORDING:all: 235 -> 999/.test(checkOut), checkOut.slice(0, 300));
  ok('--check wrote nothing to index.html', sha('index.html') === beforeIndex);

  // ── step 2: run the one command ─────────────────────────────────────────────────────────
  console.log('\n2. `sync-prices` applies it');
  fs.copyFileSync('index.html', TEST_PAGE);
  const out = execFileSync(process.execPath,
    ['scripts/sync-prices.mjs', '--from', tmpPrices, '--into', TEST_PAGE], { encoding: 'utf8' });
  ok('the command reports the change', /RECORDING:all: 235 -> 999/.test(out), out.slice(0, 400));
  ok('it did not silently touch other prices',
    (out.match(/->/g) || []).length === 1, out.slice(0, 400));
  ok('the real index.html is untouched', sha('index.html') === beforeIndex);
  ok('and data/prices.json is untouched — this repo never writes it', sha('data/prices.json') === beforePrices);
  ok('the synced page really changed', sha(TEST_PAGE) !== beforeIndex);

  // ── step 3: the number a counselor actually sees ─────────────────────────────────────────
  console.log('\n3. The new number reaches the screen');
  browser = await chromium.launch();
  const ctx = await browser.newContext();
  await ctx.route(/gstatic\.com\/firebasejs/, (r) => r.abort());
  const page = await ctx.newPage();
  await page.addInitScript(FAKE);
  await page.addInitScript(`window.__fake.addAccount('t@bwquote.local','pw');`);
  await page.goto('http://localhost:3737/' + TEST_PAGE, { waitUntil: 'load', timeout: 120000 });
  await page.evaluate(() => _fbAuth.signInWithEmailAndPassword('t@bwquote.local', 'pw'));
  await page.waitForFunction(() => window._fbQuotesReady === true, { timeout: 20000 });

  const r = await page.evaluate(async () => {
    show('cem-quote', null);
    const g = document.getElementById('qGarden');
    g.value = [...g.options].find((o) => /\|/.test(o.value)).value;
    document.getElementById('qRecGround').checked = true;
    document.getElementById('qBurialArrange').checked = true;
    cemUpdateD();
    await new Promise((res) => setTimeout(res, 300));
    const lines = {};
    (_cemLines || []).forEach((l) => { lines[l.label] = l.amount; });
    buildPriceIndex();
    const drift = await window.bwVerifyPriceFile();
    return {
      fee: window.BW_FEES['RECORDING:all'],
      stamp: window.BW_PRICES_GENERATED,
      groupLabel: [...document.querySelectorAll('#section-cem-quote .q-group-label')]
        .map((n) => n.textContent).find((t) => /Recording Fees/.test(t)),
      // the quick-reference card. textContent, not innerText: show('cem-quote') hides the
      // panel it lives in, and innerText returns '' for anything not laid out.
      card: (function () {
        var s = document.querySelector('strong > [data-fee="RECORDING:all"]');
        if (!s) return null;
        return (s.closest('div').textContent || '').replace(/\s+/g, ' ').trim();
      })(),
      quoted: lines['Recording Fee – Interment'],
      bundle: (document.getElementById('qBurialArrangeDisp') || {}).textContent,
      indexed: PRICE_INDEX.filter((i) => /^Recording Fees$/.test(i.name)).map((i) => i.price),
      drift,
      banner: (document.getElementById('bwPriceBanner') || {}).textContent || '',
    };
  });

  ok('BW_FEES holds the new amount', r.fee === NEW_RECORDING, r.fee);
  ok('the generated stamp came across too', r.stamp === '2026-07-27', r.stamp);
  ok('the checkbox group label reads it', /\$999 each/.test(r.groupLabel || ''), r.groupLabel);
  ok('the quick-reference card reads it', /Recording Fee: \$999\b/.test(r.card || ''), r.card);
  ok('a quoted line uses it', r.quoted === NEW_RECORDING, r.quoted);
  ok('and so does the Standard Burial bundle (2305+685+999+1535 = 5,524)',
    /5,?524/.test(r.bundle || ''), r.bundle);
  ok('the Price List picked up the new price', JSON.stringify(r.indexed) === '[999]', r.indexed);

  // The runtime guard, seen from the wrong side on purpose: this page quotes 999 while the
  // deployed data/prices.json still says 235, which is exactly the deploy-one-file-not-the-
  // other case. It has to be loud.
  console.log('\n4. The runtime guard notices a page that disagrees with the deployed file');
  ok('bwVerifyPriceFile() reports the disagreement', Array.isArray(r.drift) && r.drift.length === 1, r.drift);
  ok('naming the key and both amounts',
    /RECORDING:all.*235.*999/.test((r.drift || []).join('')), r.drift);
  ok('and it shows a banner naming the file', /data\/prices\.json/.test(r.banner), r.banner.slice(0, 200));

  console.log('\n5. Reverting is just running it again against the real file');
  execFileSync(process.execPath, ['scripts/sync-prices.mjs', '--into', TEST_PAGE], { encoding: 'utf8' });
  ok('the synced page is byte-identical to index.html again', sha(TEST_PAGE) === beforeIndex);
  ok('the recording fee is back to ' + oldRecording,
    fs.readFileSync(TEST_PAGE, 'utf8').indexOf("'RECORDING:all': " + oldRecording + ',') > -1);
} finally {
  if (browser) await browser.close();
  try { fs.rmSync(TEST_PAGE, { force: true }); } catch (e) { /* ignore */ }
  try { fs.rmSync(tmp, { recursive: true, force: true }); } catch (e) { /* ignore */ }
}

ok('index.html was never modified by this suite', sha('index.html') === beforeIndex);
ok('data/prices.json was never modified by this suite', sha('data/prices.json') === beforePrices);
ok('the temporary page was cleaned up', !fs.existsSync(TEST_PAGE));

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
